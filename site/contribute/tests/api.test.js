import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

import {
  MOCK_KEY,
  SendError,
  createMockSender,
  createSender,
  submitBatch,
} from "../js/api.js";
import { BATCH_SIZE, advance, createState, currentWordId, saveAnswer, startBatch } from "../js/logic.js";

const pool = JSON.parse(readFileSync(new URL("../words.json", import.meta.url), "utf8"));
const AR = String.fromCodePoint(0x0645, 0x0631, 0x062d, 0x0628, 0x0627);
const CFG = { url: "https://abc.supabase.co", key: "anon-test-key" };

const res = (status, body) => ({
  ok: status >= 200 && status < 300,
  status,
  json: async () => {
    if (body === undefined) throw new SyntaxError("no body");
    return body;
  },
});
const dup = (constraint) =>
  res(409, { code: "23505", message: `duplicate key value violates unique constraint "${constraint}"` });

/** fetch stub: replays the given responses (or Errors to throw) in order. */
function stubFetch(...replies) {
  const calls = [];
  const fn = async (url, init) => {
    calls.push({ url, init, body: JSON.parse(init.body) });
    const r = replies.shift();
    if (r === undefined) throw new Error("unexpected extra request");
    if (r instanceof Error) throw r;
    return r;
  };
  fn.calls = calls;
  return fn;
}

/** A state with a full batch of 10 answers, ready to send. */
function readyState() {
  const s = createState();
  s.intro = { name: "Zed", email: "z@example.org", country: "SA", countryOther: "", credit: true, consent: true };
  startBatch(s, pool);
  for (let i = 0; i < BATCH_SIZE; i += 1) {
    saveAnswer(s, currentWordId(s), {
      arabic: AR, arabizi: "x", arabicFeminine: null, arabiziFeminine: null, keptInEnglish: false,
    });
    advance(s, pool);
  }
  return s;
}

const tables = (fetchFn) => fetchFn.calls.map((c) => c.url.split("/rest/v1/")[1]);

test("success: contributor 201 then entries 201", async () => {
  const f = stubFetch(res(201), res(201));
  const s = readyState();
  assert.equal(await submitBatch(s, createSender(CFG, f)), "sent");
  assert.deepEqual(tables(f), ["contributors", "entries"]);
  const [c, e] = f.calls;
  assert.equal(c.init.method, "POST");
  assert.equal(c.init.headers.Prefer, "return=minimal");
  assert.equal(c.init.headers.apikey, CFG.key);
  assert.equal(c.init.headers.Authorization, `Bearer ${CFG.key}`);
  assert.equal(c.init.credentials, "omit");
  assert.equal(c.body.name, "Zed");
  assert.equal(c.body.credit_by_name, true);
  assert.equal(c.body.country, "SA");
  assert.equal(c.body.country_other, null);
  assert.equal("dialect" in c.body, false, "dialect is generated by the database, never sent");
  assert.equal(e.body.length, BATCH_SIZE);
  assert.ok(e.body.every((row) => row.contributor_id === c.body.id));
  assert.equal(s.screen, "done");
  assert.equal(s.contributorSent, true);
  assert.equal(s.intro.name, "");
  assert.equal(s.intro.email, "");
});

test("publishable key goes only in the apikey header", async () => {
  const f = stubFetch(res(201));
  await createSender({ ...CFG, key: "sb_publishable_abc" }, f).sendContributor({ id: "x" });
  assert.equal(f.calls[0].init.headers.apikey, "sb_publishable_abc");
  assert.equal("Authorization" in f.calls[0].init.headers, false);
});

test("entries fail after contributor 201: identity locked, retry sends only entries", async () => {
  const f = stubFetch(res(201), res(503), res(201));
  const sender = createSender(CFG, f);
  const s = readyState();
  const id = s.contributorId;
  let saves = 0;
  await assert.rejects(submitBatch(s, sender, () => (saves += 1)), (err) => {
    assert.ok(err instanceof SendError);
    assert.equal(err.kind, "http");
    assert.equal(err.status, 503);
    return true;
  });
  assert.equal(s.contributorSent, true, "contributor saved and locked");
  assert.equal(s.intro.email, "", "email dropped once saved");
  assert.ok(saves >= 1, "state persisted after the contributor was accepted");
  assert.equal(s.screen, "words", "batch kept for retry");
  assert.equal(await submitBatch(s, sender), "sent");
  assert.deepEqual(tables(f), ["contributors", "entries", "entries"]);
  assert.equal(f.calls[2].body[0].contributor_id, id);
});

test("lost contributor response: retry gets 409 on the primary key, accepted, then entries 201", async () => {
  const f = stubFetch(new TypeError("Failed to fetch"), dup("contributors_pkey"), res(201));
  const sender = createSender(CFG, f);
  const s = readyState();
  await assert.rejects(submitBatch(s, sender), (err) => err.kind === "network");
  assert.equal(s.contributorSent, false);
  assert.equal(await submitBatch(s, sender), "sent");
  assert.deepEqual(tables(f), ["contributors", "contributors", "entries"]);
  assert.equal(f.calls[0].body.id, f.calls[1].body.id, "same id on retry");
});

test("entries 409 duplicate on (contributor, word) is accepted as already saved", async () => {
  const f = stubFetch(res(201), dup("entries_contributor_word_key"));
  const s = readyState();
  assert.equal(await submitBatch(s, createSender(CFG, f)), "sent");
});

for (const status of [400, 401, 403, 404, 422, 500, 502, 503]) {
  test(`HTTP ${status} on contributors fails and does not lock the identity`, async () => {
    const f = stubFetch(res(status, { code: "x", message: "nope" }));
    const s = readyState();
    await assert.rejects(submitBatch(s, createSender(CFG, f)), (err) => {
      assert.equal(err.kind, "http");
      assert.equal(err.status, status);
      return true;
    });
    assert.equal(s.contributorSent, false);
    assert.equal(s.intro.name, "Zed");
    assert.equal(s.screen, "words");
  });
  test(`HTTP ${status} on entries fails`, async () => {
    const f = stubFetch(res(201), res(status, {}));
    const s = readyState();
    await assert.rejects(submitBatch(s, createSender(CFG, f)), (err) => err.status === status);
    assert.equal(s.screen, "words");
  });
}

test("network error / offline / timeout abort are SendError network", async () => {
  for (const thrown of [new TypeError("Failed to fetch"), Object.assign(new Error("x"), { name: "AbortError" })]) {
    const f = stubFetch(thrown);
    const s = readyState();
    await assert.rejects(submitBatch(s, createSender(CFG, f)), (err) => {
      assert.ok(err instanceof SendError);
      assert.equal(err.kind, "network");
      return true;
    });
    assert.equal(s.contributorSent, false);
  }
});

test("only the exact 409 duplicate case counts as already saved", async () => {
  const notSaved = [
    ["contributors", res(409, { code: "23503", message: 'violates foreign key constraint "x"' })],
    ["contributors", res(409, { code: "23505", message: 'unique constraint "other_key"' })],
    ["contributors", res(409, { code: "23505", message: 'unique constraint "contributors_pkey_v2"' })],
    ["contributors", res(409, { code: "23505", message: 'unique constraint "entries_contributor_word_key"' })],
    ["contributors", res(409, {})],
    ["contributors", res(409)],
    ["contributors", res(400, { code: "23505", message: 'unique constraint "contributors_pkey"' })],
    ["contributors", res(500, { code: "23505", message: 'unique constraint "contributors_pkey"' })],
    ["entries", res(409, { code: "23505", message: 'unique constraint "contributors_pkey"' })],
    ["entries", res(409, { code: "23503", message: 'violates foreign key constraint "entries_contributor_id_fkey"' })],
    ["entries", res(422, { code: "23505", message: 'unique constraint "entries_contributor_word_key"' })],
  ];
  for (const [table, reply] of notSaved) {
    const sender = createSender(CFG, stubFetch(reply));
    const send = table === "contributors" ? sender.sendContributor({ id: "x" }) : sender.sendEntries([{ id: "x" }]);
    await assert.rejects(send, SendError, `${table} ${reply.status} must not count as saved`);
  }
  const ok = createSender(CFG, stubFetch(dup("contributors_pkey"), dup("entries_contributor_word_key")));
  await ok.sendContributor({ id: "x" });
  await ok.sendEntries([{ id: "x" }]);
});

test("deletion_code collision: new id and code, retried once", async () => {
  const f = stubFetch(dup("contributors_deletion_code_key"), res(201), res(201));
  const s = readyState();
  const before = { id: s.contributorId, code: s.deletionCode };
  assert.equal(await submitBatch(s, createSender(CFG, f)), "sent");
  assert.deepEqual(tables(f), ["contributors", "contributors", "entries"]);
  assert.notEqual(f.calls[1].body.id, before.id);
  assert.notEqual(f.calls[1].body.deletion_code, before.code);
  assert.equal(s.deletionCode, f.calls[1].body.deletion_code, "the code shown is the one saved");
  assert.equal(f.calls[2].body[0].contributor_id, f.calls[1].body.id);
});

test("deletion_code collision twice: gives up, no loop", async () => {
  const f = stubFetch(dup("contributors_deletion_code_key"), dup("contributors_deletion_code_key"));
  const s = readyState();
  await assert.rejects(submitBatch(s, createSender(CFG, f)), (err) => err.kind === "deletion_code_conflict");
  assert.equal(f.calls.length, 2);
  assert.equal(s.contributorSent, false);
});

test("deletion_code conflict is not recognised on the entries table", async () => {
  const sender = createSender(CFG, stubFetch(dup("contributors_deletion_code_key")));
  await assert.rejects(sender.sendEntries([{ id: "x" }]), (err) => err.kind === "http");
});

