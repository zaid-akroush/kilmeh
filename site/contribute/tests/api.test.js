test("mock sender never stores name or email", async () => {
  const store = new Map();
  globalThis.sessionStorage = {
    getItem: (k) => (store.has(k) ? store.get(k) : null),
    setItem: (k, v) => store.set(k, String(v)),
  };
  const origInfo = console.info;
  console.info = () => {};
  try {
    const s = readyState();
    assert.equal(await submitBatch(s, createMockSender()), "sent");
    const raw = store.get(MOCK_KEY);
    assert.ok(!raw.includes("Zed") && !raw.includes("z@example.org"));
    const records = JSON.parse(raw);
    assert.equal(records[0].contributor.name_given, true);
    assert.equal(records[0].contributor.email_given, true);
    assert.equal(records[0].contributor.country, "SA");
    assert.equal(records[0].contributor.dialect_derived, "gulf");
    assert.equal(records[1].entries.length, BATCH_SIZE);
    assert.equal(s.intro.name, "");
  } finally {
    console.info = origInfo;
    delete globalThis.sessionStorage;
  }
});
